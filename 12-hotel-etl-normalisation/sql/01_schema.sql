-- ============================================================================
-- Hotel booking warehouse - normalised schema (0NF -> 3NF), PostgreSQL
--
-- The source is a single 49-row spreadsheet in 0NF: one wide table where every
-- descriptive attribute is repeated inline as text. Each DECISION note below
-- records which normal form the change satisfies.
--
-- Ported from MySQL. Differences that mattered:
--   * MySQL backtick quoting `booking status` -> standard double quotes, or
--     better, snake_case names that need no quoting at all
--   * AUTO_INCREMENT -> GENERATED ... AS IDENTITY
--   * MySQL tolerates mixed date strings on insert into DATE columns;
--     PostgreSQL rejects them, which forced the date parsing to be explicit
-- ============================================================================

DROP TABLE IF EXISTS booking             CASCADE;
DROP TABLE IF EXISTS guest               CASCADE;
DROP TABLE IF EXISTS dim_booking_status  CASCADE;
DROP TABLE IF EXISTS dim_booking_source  CASCADE;
DROP TABLE IF EXISTS dim_room_type       CASCADE;
DROP TABLE IF EXISTS dim_meal_plan       CASCADE;

-- ----------------------------------------------------------------------------
-- Lookup dimensions
--
-- DECISION (3NF): meal plan, room type, market source and booking status were
-- free text repeated on all 49 rows - 2, 3, 4 and 2 distinct values
-- respectively. Each describes a category, not a booking, so each becomes a
-- lookup table. Besides removing the repetition this makes the valid set
-- enforceable: the original accepted any spelling of 'Room_Type 1'.
-- ----------------------------------------------------------------------------

-- NOTE on identity columns: BY DEFAULT rather than ALWAYS. ALWAYS forbids
-- inserting an explicit id, which is the stricter and usually better choice -
-- but it also blocks a loader that assigns surrogate keys itself, which is
-- exactly what the ETL and the notebook do. BY DEFAULT keeps the sequence for
-- ordinary inserts while allowing a bulk load to supply its own ids.

CREATE TABLE dim_meal_plan (
    meal_plan_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama         varchar(30) NOT NULL UNIQUE
);

CREATE TABLE dim_room_type (
    room_type_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama         varchar(30) NOT NULL UNIQUE
);

CREATE TABLE dim_booking_source (
    source_id    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama         varchar(30) NOT NULL UNIQUE
);

CREATE TABLE dim_booking_status (
    status_id    int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama         varchar(30) NOT NULL UNIQUE
);

-- ----------------------------------------------------------------------------
-- Guest
--
-- DECISION (honest modelling): in this extract Guest_ID and Booking_ID are
-- both unique across all 49 rows - a strict 1:1 relationship. No guest appears
-- twice, so splitting guests into their own table removes no redundancy on
-- THIS data; it is a degenerate dimension.
--
-- It is kept anyway because it is the correct shape for the domain: a hotel
-- guest can obviously book more than once, and the 1:1 is an artefact of a
-- 49-row sample. The original coursework split guest attributes out and
-- described it as removing a partial dependency, which it was not - there was
-- no composite key for a partial dependency to exist against.
-- ----------------------------------------------------------------------------

CREATE TABLE guest (
    guest_id     varchar(12) PRIMARY KEY           -- 'GI00001' from the source
);

-- ----------------------------------------------------------------------------
-- Booking
--
-- DECISION (1NF): `date of reservation` held two different representations in
-- one column - 16 rows as 'yyyy-mm-dd 00:00:00' and 33 as 'm/d/yyyy'. A column
-- must hold one atomic, consistently-typed value, so it is parsed to DATE at
-- load time. MySQL silently accepted the mixed strings; PostgreSQL does not,
-- which is how the problem surfaced at all.
--
-- DECISION (1NF): `parking` held '0' / '1' as text and is now boolean.
--
-- DECISION (naming): column names with spaces ('weekend nights') required
-- backtick quoting in MySQL and would need double quotes in PostgreSQL
-- forever after. Renamed to snake_case so no query needs quoting.
-- ----------------------------------------------------------------------------

CREATE TABLE booking (
    booking_id        varchar(12) PRIMARY KEY,     -- 'INN00001'
    guest_id          varchar(12) NOT NULL REFERENCES guest(guest_id),
    meal_plan_id      int NOT NULL REFERENCES dim_meal_plan(meal_plan_id),
    room_type_id      int NOT NULL REFERENCES dim_room_type(room_type_id),
    source_id         int NOT NULL REFERENCES dim_booking_source(source_id),
    status_id         int NOT NULL REFERENCES dim_booking_status(status_id),
    reservation_date  date         NOT NULL,
    adults            smallint     NOT NULL CHECK (adults   BETWEEN 0 AND 10),
    children          smallint     NOT NULL CHECK (children BETWEEN 0 AND 10),
    weekend_nights    smallint     NOT NULL CHECK (weekend_nights BETWEEN 0 AND 14),
    week_nights       smallint     NOT NULL CHECK (week_nights    BETWEEN 0 AND 30),
    lead_time         int          NOT NULL CHECK (lead_time >= 0),
    price             numeric(10,2) NOT NULL CHECK (price >= 0),
    special_requests  smallint     NOT NULL CHECK (special_requests BETWEEN 0 AND 10),
    car_parking       boolean      NOT NULL,
    -- a booking with no nights at all is not a booking
    CHECK (weekend_nights + week_nights > 0)
);

CREATE INDEX idx_booking_date   ON booking(reservation_date);
CREATE INDEX idx_booking_status ON booking(status_id);
CREATE INDEX idx_booking_room   ON booking(room_type_id);
